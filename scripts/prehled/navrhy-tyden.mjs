// Návrhy od veřejnosti jednou týdně (RA55, #564): každé pondělí rutina založí issue „Návrhy od veřejnosti: týden
// RRRR-TT“ (štítky `interni`, `navrh`, `oblast:provoz`) se všemi otevřenými `feature-request` bez rozhodnutí.
// U každého návrhu je věta „Pro lidi“ a doporučení AI. Vlastník rozhodne jednou: `schvaleno` na týdenním issue
// a komentář „podle doporučení“, nebo řádky s čísly a rozhodnutím. AI pak rozhodnutí provede (připojí, zavře,
// přenese). Skript jen čte a skládá text; zápisy na GitHub dělá rutina podle skillu `trideni-issues`.
//
//   node scripts/prehled/navrhy-tyden.mjs --seznam                  otevřené návrhy bez rozhodnutí (JSON)
//   node scripts/prehled/navrhy-tyden.mjs --telo <doporuceni.json>  tělo týdenního issue z doporučení AI
//   node scripts/prehled/navrhy-tyden.mjs --rozhodnuti <N>          rozhodnutí vlastníka z týdenního issue #N
//
// Soubor doporučení: [{ "cislo": 123, "titulek": "…", "proLidi": "…", "doporuceni": "zařadit do celku #306" }].

import fs from 'node:fs';
import { pathToFileURL } from 'node:url';
import { REPO, vytvorApi } from '../brana/data.mjs';

export const TITULEK = 'Návrhy od veřejnosti: týden';
export const STITKY_ISSUE = ['interni', 'navrh', 'oblast:provoz'];
const BEZ_ROZHODNUTI = ['schvaleno', 'zamitnuto', 'stop', 'trvale'];
const PATICKA_AI = /Generated by \[?Claude Code/i;

/** Týden podle ISO 8601 jako „RRRR-TT“ (pondělí začíná týden, první týden obsahuje čtvrtek). */
export function tyden(datum) {
  const d = new Date(Date.UTC(datum.getUTCFullYear(), datum.getUTCMonth(), datum.getUTCDate()));
  const den = d.getUTCDay() || 7;
  d.setUTCDate(d.getUTCDate() + 4 - den);
  const zacatek = Date.UTC(d.getUTCFullYear(), 0, 1);
  const cislo = Math.ceil(((d - zacatek) / 86400000 + 1) / 7);
  return `${d.getUTCFullYear()}-${String(cislo).padStart(2, '0')}`;
}

/** Otevřené návrhy funkcí od veřejnosti, o kterých vlastník ještě nerozhodl (bez PR, bez schvaleno, zamitnuto, stop). */
export function navrhyKRozhodnuti(issues = []) {
  return issues
    .filter((i) => !i.pull_request && (i.stav || 'open') === 'open')
    .filter((i) => i.stitky.includes('feature-request') && !i.stitky.some((s) => BEZ_ROZHODNUTI.includes(s)))
    .sort((a, b) => a.cislo - b.cislo);
}

/**
 * Doporučení AI v jednotném tvaru: { akce: 'zaradit', celek } | { akce: 'spojit', s } | { akce: 'odlozit' }
 * | { akce: 'zamitnout', duvod }, nebo null, když text tvaru neodpovídá.
 */
export function ctiAkci(text = '') {
  const t = text.trim();
  let m;
  if ((m = t.match(/^zařadit\b[^#]*#(\d+)/i))) return { akce: 'zaradit', celek: Number(m[1]) };
  if ((m = t.match(/^spojit\b[^#]*#(\d+)/i))) return { akce: 'spojit', s: Number(m[1]) };
  if (/^odložit\b/i.test(t)) return { akce: 'odlozit' };
  if ((m = t.match(/^zamítnout\b\s*(?:\((.*)\)|[:,-]?\s*(.*))$/i))) {
    const duvod = (m[1] ?? m[2] ?? '').trim();
    return duvod ? { akce: 'zamitnout', duvod } : null;
  }
  return null;
}

export function popisAkce(a) {
  if (a.akce === 'zaradit') return `zařadit do celku #${a.celek}`;
  if (a.akce === 'spojit') return `spojit s #${a.s}`;
  if (a.akce === 'zamitnout') return `zamítnout (${a.duvod})`;
  return 'odložit';
}

const jednaVeta = (t = '') => String(t).replace(/\s+/g, ' ').trim();

/** Tělo týdenního issue. Každé doporučení musí mít platný tvar (ctiAkci), jinak vyhodí chybu. */
export function sestavTelo({ tyden: t, polozky }) {
  const radky = [
    `Návrhy nových funkcí od veřejnosti, o kterých se rozhoduje najednou jednou týdně (RA55, #564). Týden ${t}.`,
    '',
    'Pro lidi: Vlastník jednou týdně rozhodne o nápadech, které poslali návštěvníci webu.',
    '',
    '## Jak rozhodnout',
    '',
    'Přidej štítek `schvaleno` a napiš komentář: buď „podle doporučení“, nebo řádky ve tvaru',
    '`#N zařadit do #M`, `#N spojit s #M`, `#N odložit`, `#N zamítnout (důvod)`. Návrh, který v komentáři chybí,',
    'se přenese do dalšího týdne. AI rozhodnutí provede a issue zavře.',
    '',
    '## Návrhy',
    '',
  ];
  if (!polozky.length) radky.push('Tento týden žádný návrh nečeká.');
  for (const p of polozky) {
    const akce = ctiAkci(p.doporuceni);
    if (!akce) throw new Error(`#${p.cislo}: doporučení „${p.doporuceni}“ nemá tvar zařadit do #M / spojit s #M / odložit / zamítnout (důvod)`);
    radky.push(`- #${p.cislo} ${jednaVeta(p.titulek)}`);
    radky.push(`  - Pro lidi: ${jednaVeta(p.proLidi)}`);
    radky.push(`  - Doporučení: ${popisAkce(akce)}`);
  }
  return `${radky.join('\n')}\n`;
}

/** Doporučení z těla týdenního issue: Map číslo návrhu → akce. */
export function doporuceniZTela(telo = '') {
  const vysledek = new Map();
  let cislo = null;
  for (const r of telo.replace(/\r\n?/g, '\n').split('\n')) {
    const polozka = r.match(/^- #(\d+)\b/);
    if (polozka) cislo = Number(polozka[1]);
    const dop = r.match(/^\s+- Doporučení:\s*(.+)$/);
    if (dop && cislo) {
      const a = ctiAkci(dop[1]);
      if (a) vysledek.set(cislo, a);
    }
  }
  return vysledek;
}

/**
 * Poslední komentář vlastníka bez patičky AI, nebo komentář s nadpisem „Odpověď vlastníka“ od vlastníka či asistenta
 * (zápis jeho odpovědi); od jiných účtů se nadpis neuznává. Vrací null, když chybí.
 */
export function komentarVlastnika(komentare = [], vlastnik = 'tangero', asistent = 'eduarda-prijimacky') {
  return [...komentare].reverse().find((k) => ((k.autor === vlastnik || k.autor === asistent)
      && /^#{0,6}\s*Odpověď vlastníka/im.test(k.telo || ''))
    || (k.autor === vlastnik && !PATICKA_AI.test(k.telo || ''))) || null;
}

/**
 * Rozhodnutí vlastníka z komentáře. „podle doporučení“ převezme všechna doporučení; řádky `#N akce` je přepíšou.
 * Návrh bez rozhodnutí se odloží (přenese do dalšího týdne). Vrací { rozhodnuti: Map, nejasne: [řádky] }.
 */
export function ctiRozhodnuti(text = '', doporuceni = new Map()) {
  const rozhodnuti = new Map();
  const nejasne = [];
  if (/podle doporučení/i.test(text)) for (const [n, a] of doporuceni) rozhodnuti.set(n, a);
  for (const r of text.replace(/\r\n?/g, '\n').split('\n')) {
    const m = r.match(/^\s*[-*]?\s*#(\d+)\s*[:–-]?\s*(.+)$/);
    if (!m) continue;
    const a = ctiAkci(m[2]);
    if (a) rozhodnuti.set(Number(m[1]), a);
    else nejasne.push(r.trim());
  }
  for (const n of doporuceni.keys()) if (!rozhodnuti.has(n)) rozhodnuti.set(n, { akce: 'odlozit' });
  return { rozhodnuti, nejasne };
}

async function main() {
  const api = vytvorApi();
  const argv = process.argv.slice(2);
  if (argv[0] === '--seznam') {
    const vse = [];
    for (let strana = 1; strana <= 10; strana++) {
      const dil = await api(`repos/${REPO}/issues?state=open&labels=feature-request&per_page=100&page=${strana}`);
      vse.push(...dil);
      if (dil.length < 100) break;
    }
    const navrhy = navrhyKRozhodnuti(vse.map((i) => ({
      cislo: i.number, titulek: i.title, stitky: i.labels.map((l) => l.name), stav: i.state, pull_request: i.pull_request,
    })));
    return console.log(JSON.stringify(navrhy.map(({ cislo, titulek }) => ({ cislo, titulek })), null, 2));
  }
  if (argv[0] === '--telo' && argv[1]) {
    const polozky = JSON.parse(fs.readFileSync(argv[1], 'utf8'));
    return process.stdout.write(sestavTelo({ tyden: tyden(new Date()), polozky }));
  }
  if (argv[0] === '--rozhodnuti' && argv[1]) {
    const cislo = Number(argv[1]);
    const i = await api(`repos/${REPO}/issues/${cislo}`);
    const stitky = i.labels.map((l) => l.name);
    if (!stitky.includes('schvaleno')) return console.log(`#${cislo}: bez štítku schvaleno, vlastník ještě nerozhodl.`);
    const komentare = (await api(`repos/${REPO}/issues/${cislo}/comments?per_page=100`)).map((k) => ({ autor: k.user?.login, telo: k.body || '' }));
    const yaml = (await import('js-yaml')).default;
    const rezimy = yaml.load(Buffer.from((await api(`repos/${REPO}/contents/.github/rezimy.yml?ref=main`)).content, 'base64').toString('utf8'));
    const k = komentarVlastnika(komentare, rezimy.vlastnik, rezimy.asistent);
    if (!k) return console.log(`#${cislo}: schvaleno bez komentáře s rozhodnutím; zeptej se vlastníka (štítek otazka).`);
    const { rozhodnuti, nejasne } = ctiRozhodnuti(k.telo, doporuceniZTela(i.body || ''));
    for (const [n, a] of rozhodnuti) console.log(`#${n}: ${popisAkce(a)}`);
    for (const r of nejasne) console.log(`nejasné: ${r}`);
    return;
  }
  console.error('Použití: --seznam | --telo <doporuceni.json> | --rozhodnuti <N>');
  process.exit(2);
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
