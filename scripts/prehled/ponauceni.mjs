/**
 * Výstup modelu → { navrhy, vyrazeno } nebo null (neplatný tvar). Návrh projde, jen když:
 * má platný klíč a cílový soubor pravidel, jeho doklady jsou čísla ze signálů selhání agenta (žádné vymyšlené
 * odkazy), má aspoň dva doklady nebo věcnou škodu (K3) a klíč není v evidenci (K4). Nejvýš MAX_NAVRHU.
 */
export function overNavrhy(surovy, signaly, evidence = novaEvidence()) {
  if (typeof surovy !== 'string' || !surovy.trim()) return null;
  const blok = surovy.match(/```(?:json)?\s*([\s\S]*?)```/i)?.[1] ?? surovy;
  const od = blok.indexOf('{');
  const po = blok.lastIndexOf('}');
  if (od < 0 || po < od) return null;
  let data;
  try { data = JSON.parse(blok.slice(od, po + 1)); } catch { return null; }
  if (!data || !Array.isArray(data.navrhy)) return null;
  const zname = new Set(signaly.map((s) => s.cislo));
  const navrhy = [];
  const vyrazeno = [];
  for (const n of data.navrhy) {
    if (!n || typeof n !== 'object') { vyrazeno.push({ duvod: 'neplatný tvar' }); continue; }
    const klic = String(n.klic || '').toLowerCase();
    if (!/^[a-z0-9][a-z0-9-]{2,59}$/.test(klic)) { vyrazeno.push({ klic, duvod: 'neplatný klíč' }); continue; }
    if (evidence.navrhy[klic]) { vyrazeno.push({ klic, duvod: `už v evidenci (${evidence.navrhy[klic].stav})` }); continue; }
    const soubor = String(n.soubor || '');
    if (soubor !== 'CLAUDE.md' && !/^\.claude\/skills\/[\w-]+\/SKILL\.md$/.test(soubor)) { vyrazeno.push({ klic, duvod: 'cíl není CLAUDE.md ani skill' }); continue; }
    const doklady = [...new Set((Array.isArray(n.doklady) ? n.doklady : []).map(Number).filter((c) => zname.has(c)))];
    const skoda = typeof n.skoda === 'string' && n.skoda.trim() && n.skoda.trim() !== 'null' ? bezpecnyUryvek(n.skoda, 300) : null;
    if (!doklady.length || (doklady.length < 2 && !skoda)) { vyrazeno.push({ klic, duvod: 'méně než dva doklady bez věcné škody' }); continue; }
    const zmena = odstranOsobni(String(n.zmena || '')).replace(/<!--[\s\S]*?-->/g, '').replace(/```/g, "'''").split('\n').slice(0, 20).join('\n').slice(0, 1500).trim();
    if (!zmena) { vyrazeno.push({ klic, duvod: 'chybí navržené znění' }); continue; }
    if (navrhy.length >= MAX_NAVRHU) { vyrazeno.push({ klic, duvod: 'nad počet návrhů' }); continue; }
    navrhy.push({
      klic, soubor, doklady, skoda, zmena,
      nazev: bezpecnyUryvek(n.nazev || klic, 120),
      co: bezpecnyUryvek(n.co, 400),
      pravidlo: bezpecnyUryvek(n.pravidlo, 300),
    });
  }
  return { navrhy, vyrazeno };
}

/** Volání modelu přes OpenRouter (vzor triáže); bez klíče vyhodí chybu „chybí OPENROUTER_API_KEY“. */
export async function volejModel(zpravy, { klic = process.env.OPENROUTER_API_KEY, fetchFn = globalThis.fetch } = {}) {
  if (!klic) throw new Error('chybí OPENROUTER_API_KEY');
  const odp = await fetchFn('https://openrouter.ai/api/v1/chat/completions', {
    method: 'POST',
    headers: { authorization: `Bearer ${klic}`, 'content-type': 'application/json' },
    body: JSON.stringify({ model: MODEL, messages: zpravy, max_tokens: 8000 }),
    signal: AbortSignal.timeout(180000),
  });
  if (!odp.ok) throw new Error(`OpenRouter: ${odp.status}`);
  return (await odp.json()).choices?.[0]?.message?.content ?? '';
}

/**
 * Celé ponaučení týdne: signály, rozhodnutí z evidence, návrhy modelu. Nic nezapisuje; vrátí i `novyStav`
 * a `ulozeni`, které po odeslání přehledu uloží `ulozEvidenci` (při běhu nanečisto se neukládá).
 * `model(zpravy)` → text; chyba modelu nebo chybějící klíč nechá oddíl jen se signály.
 */
export async function pripravPonauceni(api, ted, ucty, { model = volejModel, pravidla = () => nactiPravidla() } = {}) {
  const { signaly, prostredi } = await sberSignalu(api, ted, ucty);
  const ulozeni = await nactiEvidenci(api);
  const stav = JSON.parse(JSON.stringify(ulozeni.stav));
  stav.navrhy ||= {};
  const zmenRozhodnuti = prevezmiRozhodnuti(stav, ulozeni.komentare, ucty);
  let navrhy = [];
  let vyrazeno = [];
  let stavModelu = 'bez signálů';
  if (signaly.length) {
    try {
      const vysledek = overNavrhy(await model(sestavZpravy(signaly, { pravidla: pravidla(), evidence: stav })), signaly, stav);
      if (!vysledek) stavModelu = 'výstup modelu je neplatný';
      else { ({ navrhy, vyrazeno } = vysledek); stavModelu = 'ok'; }
    } catch (e) {
      stavModelu = `model nedostupný (${bezpecnyUryvek(e.message || e, 120)})`;
    }
  }
  zapisNavrhy(stav, navrhy, ted);
  const zmeneno = zmenRozhodnuti > 0 || navrhy.length > 0;
  return { signaly, prostredi, navrhy, vyrazeno, model: stavModelu, evidence: ulozeni.issue, novyStav: zmeneno ? stav : null, ulozeni };
}

