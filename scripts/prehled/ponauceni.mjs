const DEN = 24 * 60 * 60 * 1000;

/** Model návrhů (rozhodnutí vlastníka v #521: Codex od OpenAI přes OpenRouter); přepis proměnnou prostředí. */
export const MODEL = process.env.PONAUCENI_MODEL || 'openai/gpt-5.3-codex';
export const MAX_NAVRHU = 3;
export const MAX_URYVEK = 200;
export const NAZEV_EVIDENCE = 'Ponaučení: evidence návrhů';
export const ZNACKA_EVIDENCE = 'ponauceni:stav';

/** Druhy signálů selhání agenta; `prostredi` je zvlášť a do selhání agenta se nepočítá (K5). */
export const DRUHY = {
  'potrebuje-cloveka': 'PR se štítkem potrebuje-cloveka (smyčka oprav z review skončila)',
  'kola-oprav': 'sloučené PR s koly oprav z review',
  'zavreno-bez-slouceni': 'PR zavřené bez sloučení',
  'odpoved-vlastnika': 'komentáře vlastníka k postupu AI',
  'kontrola-neprosla': 'neúspěšné kontroly (testy, brána) s věcnou chybou',
  'review-nalezy': 'automatické review s nálezy k opravě',
};

const PATICKA_AI = /Generated by \[?Claude Code|Zapsal Claude Code|— Eduarda \(AI|Co-Authored-By: Claude/i;
const ODPOVED = /^#{1,3}[ \t]*Odpověď vlastníka/im;
const KOLO = /<!-- oprava-z-review:kolo=(\d+) -->/;
// Selhání prostředí: limit nebo kvóta modelu, odpověď 429/5xx, výpadek nebo nedostupnost API, vypršený čas.
const PROSTREDI = /\blimit|\bkvót|quota|rate.?limit|\b429\b|\b50[0234]\b|timed?.?out|timeout|vypršel|ECONN|ETIMEDOUT|ENOTFOUND|výpad|nedostupn|Review se nepodařilo/i;

// ---- Čištění textů (P2) ----

/** Text zbavený HTML komentářů, zmínek účtů, e-mailů a telefonů, na jeden řádek a zkrácený. */
export function bezpecnyUryvek(text = '', max = MAX_URYVEK) {
  const t = odstranOsobni(String(text))
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .replace(/```[\s\S]*?```/g, ' [kód] ')
    .replace(/(^|[^\w`])@[A-Za-z0-9][\w-]*(\[bot\])?/g, '$1[účet]')
    .replace(/[<>]/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  return t.length > max ? `${t.slice(0, max - 1)}…` : t;
}

/** Komentář vlastníka (bez patičky AI), nebo zápis „Odpověď vlastníka“ od vlastníka či asistenta. */
export function jeKomentarVlastnika(k, { vlastnik, asistent }) {
  const telo = k.body || '';
  const autor = k.user?.login;
  if (autor === vlastnik && (ODPOVED.test(telo) || !PATICKA_AI.test(telo))) return true;
  return autor === asistent && ODPOVED.test(telo);
}

/** Je text chyby selháním prostředí (limit modelu, výpadek API), ne věcnou chybou práce agenta? */
export const jeProstredi = (text = '') => PROSTREDI.test(text);

/**
 * Kontroly, které posuzují práci agenta (joby workflow Testy a brána). Ostatní (nasazení náhledu na Vercel, Tabule)
 * selhávají i z důvodů mimo PR, třeba po smazání větve sloučeného PR, a za selhání agenta se nepočítají.
 */
export const KONTROLY_PRACE = ['Python testy a kontroly dat', 'TypeScript', 'Integrace katalogu', 'Brána sloučení'];

/**
 * Kontrola na hlavě PR → null (nic), 'prostredi' nebo 'kontrola-neprosla'.
 * Brána, která čeká na souhlas vlastníka nebo na lhůtu, není selhání.
 */
export function klasifikujKontrolu(k) {
  if (!KONTROLY_PRACE.includes(k.name)) return null;
  if (k.conclusion === 'timed_out') return 'prostredi';
  if (!['failure', 'action_required', 'startup_failure'].includes(k.conclusion)) return null;
  const text = `${k.output?.title || ''}\n${k.output?.summary || ''}`;
  if (/chybí souhlas vlastníka|Čeká na lhůtu/i.test(text)) return null;
  if (k.conclusion === 'startup_failure' || jeProstredi(text)) return 'prostredi';
  return 'kontrola-neprosla';
}

/** Komentář automatického review → null, 'prostredi' (model selhal) nebo 'review-nalezy'. */
export function klasifikujReview(k, { automatika, znacka }) {
  const telo = k.body || '';
  if (k.user?.login !== automatika || !znacka || !telo.includes(znacka) || !/^## Review/m.test(telo)) return null;
  if (/Verdikt: Review se nepodařilo/.test(telo)) return 'prostredi';
  if (/Verdikt: Nálezy k opravě/.test(telo)) return 'review-nalezy';
  return null;
}

// ---- Sběr signálů (K1, K5) ----

async function strankuj(api, cesta, staci = () => false) {
  const vse = [];
  for (let strana = 1; strana <= 20; strana++) {
    const dil = await api(`${cesta}${cesta.includes('?') ? '&' : '?'}per_page=100&page=${strana}`);
    vse.push(...dil);
    if (dil.length < 100 || staci(dil)) break;
  }
  return vse;
}

const cisloZAdresy = (url = '') => Number(url.match(/\/(?:issues|pull)\/(\d+)/)?.[1]) || null;

/**
 * Signály o selhání práce agentů za 7 dní před `ted`, jen z GitHubu tohoto repozitáře.
 * Vrací { od, ted, signaly, prostredi }: `signaly` jsou selhání agenta podle druhu, `prostredi` selhání
 * prostředí, která se nepočítají. Položka: { druh, cislo, pr, titulek?, text?, kol?, kontrola? }.
 */
export async function sberSignalu(api, ted, { vlastnik, asistent, automatika, znacka } = {}) {
  const od = ted - 7 * DEN;
  const vTydnu = (iso) => iso && Date.parse(iso) >= od && Date.parse(iso) <= ted;
  const signaly = [];
  const prostredi = [];
  const klice = new Set();
  const pridej = (cil, s) => {
    const k = `${s.druh}|${s.cislo}|${s.kontrola || ''}`;
    if (klice.has(k)) return;
    klice.add(k);
    cil.push(s);
  };

  const zavrene = (await strankuj(api, `repos/${REPO}/pulls?state=closed&sort=updated&direction=desc`,
    (dil) => Date.parse(dil[dil.length - 1].updated_at) < od)).filter((p) => vTydnu(p.closed_at));
  const otevrene = (await strankuj(api, `repos/${REPO}/pulls?state=open&sort=updated&direction=desc`,
    (dil) => Date.parse(dil[dil.length - 1].updated_at) < od)).filter((p) => vTydnu(p.updated_at));
  // Automatické obnovy dat od botů nejsou práce agenta: jejich PR do signálů nevstupují vůbec.
  const odBota = new Set([...zavrene, ...otevrene].filter((p) => p.user?.type === 'Bot').map((p) => p.number));
  const titulky = new Map([...zavrene, ...otevrene].map((p) => [p.number, bezpecnyUryvek(p.title, 100)]));
  const sig = (druh, cislo, pr, navic = {}) => ({ druh, cislo, pr, titulek: titulky.get(cislo) || '', ...navic });

  for (const p of zavrene) {
    if (!p.merged_at && !odBota.has(p.number)) pridej(signaly, sig('zavreno-bez-slouceni', p.number, true));
  }
  for (const p of [...zavrene, ...otevrene]) {
    if ((p.labels || []).some((l) => l.name === 'potrebuje-cloveka')) pridej(signaly, sig('potrebuje-cloveka', p.number, true));
  }

  // Komentáře celého repozitáře za týden jedním stránkovaným dotazem: kola oprav, review, slova vlastníka.
  const komentare = (await strankuj(api, `repos/${REPO}/issues/comments?since=${new Date(od).toISOString()}&sort=created&direction=asc`))
    .filter((k) => vTydnu(k.created_at));
  const kola = new Map();
  const slouceneCisla = new Set(zavrene.filter((p) => p.merged_at).map((p) => p.number));
  for (const k of komentare) {
    const cislo = cisloZAdresy(k.html_url || k.issue_url);
    if (!cislo || odBota.has(cislo)) continue;
    const pr = /\/pull\//.test(k.html_url || '');
    const kolo = Number(k.body?.match(KOLO)?.[1]);
    if (kolo) kola.set(cislo, Math.max(kola.get(cislo) || 0, kolo));
    const review = klasifikujReview(k, { automatika, znacka });
    if (review === 'prostredi') pridej(prostredi, sig('prostredi', cislo, true, { kontrola: 'Review' }));
    else if (review) pridej(signaly, sig(review, cislo, true));
    if (jeKomentarVlastnika(k, { vlastnik, asistent })) {
      const text = bezpecnyUryvek(k.body);
      if (text) signaly.push(sig('odpoved-vlastnika', cislo, pr, { text }));
    }
  }
  for (const [cislo, kol] of kola) {
    if (slouceneCisla.has(cislo)) pridej(signaly, sig('kola-oprav', cislo, true, { kol }));
  }

  // Kontroly na poslední hlavě každého PR, se kterým se v týdnu pracovalo.
  for (const p of [...zavrene, ...otevrene]) {
    const sha = p.head?.sha;
    if (!sha || odBota.has(p.number)) continue;
    const behy = (await api(`repos/${REPO}/commits/${sha}/check-runs?filter=latest&per_page=100`)).check_runs || [];
    for (const k of behy) {
      const druh = klasifikujKontrolu(k);
      if (druh === 'prostredi') pridej(prostredi, sig('prostredi', p.number, true, { kontrola: k.name }));
      else if (druh) pridej(signaly, sig(druh, p.number, true, { kontrola: k.name }));
    }
  }

  return { od, ted, signaly, prostredi };
}

/** Signály seskupené podle druhu (v pořadí DRUHY). */
export function podleDruhu(signaly) {
  const vysledek = {};
  for (const druh of Object.keys(DRUHY)) {
    const s = signaly.filter((x) => x.druh === druh);
    if (s.length) vysledek[druh] = s;
  }
  return vysledek;
}

// ---- Evidence návrhů (K4) ----

export const novaEvidence = () => ({ verze: 1, navrhy: {} });

/**
 * Rozhodnutí vlastníka z komentářů v issue evidence: řádek `zamítnuto: <klíč>` nebo `přijato: <klíč>`
 * v komentáři vlastníka (nebo v zápisu „Odpověď vlastníka“). Upraví `stav` na místě, vrátí počet změn.
 */
export function prevezmiRozhodnuti(stav, komentare, ucty) {
  let zmen = 0;
  for (const k of komentare) {
    if (!jeKomentarVlastnika(k, ucty)) continue;
    for (const [, slovo, klic] of (k.body || '').matchAll(/^\s*(zamítnuto|zamitnuto|přijato|prijato)\s*:\s*`?([a-z0-9-]+)`?\s*$/gim)) {
      const novy = /^zam/i.test(slovo) ? 'zamitnuto' : 'prijato';
      const z = stav.navrhy[klic] || { nazev: '', navrzeno: null };
      if (z.stav !== novy) {
        stav.navrhy[klic] = { ...z, stav: novy, rozhodnuto: k.created_at?.slice(0, 10) || null };
        zmen++;
      }
    }
  }
  return zmen;
}

/** Zapíše návrhy, které šly do přehledu, jako navržené (zamítnuté a přijaté nepřepíše). */
export function zapisNavrhy(stav, navrhy, ted) {
  for (const n of navrhy) {
    if (stav.navrhy[n.klic]) continue;
    stav.navrhy[n.klic] = { stav: 'navrzeno', nazev: n.nazev, navrzeno: new Date(ted).toISOString().slice(0, 10) };
  }
  return stav;
}

export async function nactiEvidenci(api) {
  const issues = await api(`repos/${REPO}/issues?state=open&labels=oblast:provoz&per_page=100`);
  const issue = issues.find((i) => !i.pull_request && i.title === NAZEV_EVIDENCE);
  if (!issue) return { issue: null, komentar: null, stav: novaEvidence(), komentare: [] };
  const komentare = await strankuj(api, `repos/${REPO}/issues/${issue.number}/comments`);
  const k = komentare.find((x) => x.body?.includes(`<!-- ${ZNACKA_EVIDENCE}`));
  const json = k?.body.match(/```json\n([\s\S]*?)\n```/)?.[1];
  let stav = novaEvidence();
  try { if (json) stav = JSON.parse(json); } catch { /* poškozený stav: začne se znovu, navržené se ukážou znovu */ }
  return { issue: issue.number, komentar: k?.id || null, stav, komentare };
}

const teloEvidence = (stav) => `<!-- ${ZNACKA_EVIDENCE} -->\nEvidence návrhů ponaučení (zapisuje workflow Týdenní přehled, neupravovat). `
  + 'Zamítnutí nebo přijetí napiš do nového komentáře řádkem `zamítnuto: <klíč>` nebo `přijato: <klíč>`.\n\n'
  + `\`\`\`json\n${JSON.stringify(stav, null, 1)}\n\`\`\``;

/** Uloží evidenci do stavového komentáře; jediný zápis celého modulu (P1: žádné soubory, žádné PR). */
export async function ulozEvidenci(api, ulozeni, stav) {
  let { issue } = ulozeni;
  if (!issue) {
    const i = await api(`repos/${REPO}/issues`, { method: 'POST', body: {
      title: NAZEV_EVIDENCE,
      body: 'Úložiště evidence návrhů ponaučení z týdenního přehledu (#521). Stavový komentář přepisuje workflow Týdenní přehled; '
        + 'issue nezavírat. Rozhodnutí o návrhu napiš komentářem s řádkem `zamítnuto: <klíč>` nebo `přijato: <klíč>`. '
        + 'Přijatý návrh realizuje AI jako běžné zadání přes bránu.',
      labels: ['interni', 'trvale', 'oblast:provoz'],
    } });
    issue = i.number;
  }
  if (ulozeni.komentar) await api(`repos/${REPO}/issues/comments/${ulozeni.komentar}`, { method: 'PATCH', body: { body: teloEvidence(stav) } });
  else await api(`repos/${REPO}/issues/${issue}/comments`, { method: 'POST', body: { body: teloEvidence(stav) } });
  return issue;
}

