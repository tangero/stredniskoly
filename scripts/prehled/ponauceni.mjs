/** Jedna věta do Telegramu. */
export function kratkaPonauceni(p) {
  if (!p || p.chyba) return '';
  if (p.navrhy.length) return `Ponaučení: ${p.navrhy.length} ${p.navrhy.length === 1 ? 'návrh' : 'návrhy'} změny pravidel AI v celém přehledu, rozhoduješ ty`;
  if (p.signaly.length) return `Ponaučení: žádný návrh, signálů selhání agentů ${p.signaly.length}`;
  return '';
}

/** Oddíl Ponaučení dlouhého přehledu. */
export function oddilPonauceni(p, odkazFn = (n) => `#${n}`) {
  if (!p) return [];
  if (p.chyba) return ['## Ponaučení', `- nepodařilo se načíst: ${p.chyba}`, ''];
  const o = (s) => odkazFn(s.cislo, s.pr);
  const radky = [
    '## Ponaučení',
    'Návrhy změny pravidel AI (`CLAUDE.md`, skills) podle doložených selhání práce agentů za týden. Nic se nepřepisuje: '
      + 'přijatý návrh udělá AI na tvůj pokyn jako běžné zadání přes bránu.',
    '',
  ];
  if (!p.signaly.length) {
    radky.push('- žádné ponaučení (žádný signál selhání agentů)');
  } else if (p.navrhy.length) {
    p.navrhy.forEach((n, i) => {
      radky.push(
        `### ${i + 1}. ${n.nazev} (\`${n.klic}\`)`,
        `- Co se stalo: ${n.co}`,
        `- Doklady: ${n.doklady.map((c) => odkazFn(c, p.signaly.find((s) => s.cislo === c)?.pr)).join(', ')}${n.skoda ? `; věcná škoda: ${n.skoda}` : ''}`,
        `- Pravidlo: ${n.pravidlo}`,
        `- Navržená změna \`${n.soubor}\`:`,
        '',
        '```diff',
        n.zmena,
        '```',
        '',
      );
    });
    radky.push(p.evidence
      ? `Zamítnutí nebo přijetí zapiš komentářem v ${odkazFn(p.evidence)} řádkem \`zamítnuto: <klíč>\` nebo \`přijato: <klíč>\`; navržené se znovu nenavrhuje.`
      : 'Zamítnutí nebo přijetí zapiš komentářem v issue „Ponaučení: evidence návrhů“ řádkem `zamítnuto: <klíč>` nebo `přijato: <klíč>`.');
  } else {
    radky.push(p.model === 'ok'
      ? '- žádné ponaučení (žádný návrh nesplnil podmínku dvou dokladů nebo věcné škody)'
      : `- žádné ponaučení: návrhy nejsou, ${p.model}; níže jen výpis signálů`);
  }
  if (p.signaly.length) {
    radky.push('', '### Signály selhání agentů');
    for (const [druh, s] of Object.entries(podleDruhu(p.signaly))) {
      const polozky = s.slice(0, 15).map((x) => `${o(x)}${x.kol ? ` (${x.kol} kol)` : ''}${x.kontrola ? ` (${bezpecnyUryvek(x.kontrola, 60)})` : ''}`);
      radky.push(`- ${DRUHY[druh]}: ${polozky.join(', ')}${s.length > 15 ? ` a dalších ${s.length - 15}` : ''}`);
    }
  }
  if (p.prostredi?.length) {
    radky.push(`- selhání prostředí (limit modelu, výpadek API; do selhání agentů se nepočítají): ${p.prostredi.map((x) => `${o(x)} (${bezpecnyUryvek(x.kontrola || '', 60)})`).join(', ')}`);
  }
  radky.push('');
  return radky;
}
