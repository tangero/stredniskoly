// Ponaučení ze selhání agentů (#521): týdenní sběr signálů o selhání práce AI v tomto repozitáři, z nich
// nejvýš 3 návrhy změny pravidel (`CLAUDE.md`, skills) od modelu Codex přes OpenRouter a evidence návrhů,
// aby se zamítnuté a už navržené neopakovaly. Oddíl „Ponaučení“ skládá týdenní přehled (tydenni.mjs).
//
// Pojistky:
// - Jen čtení GitHubu tohoto repozitáře; jediný zápis je stavový komentář v issue „Ponaučení: evidence návrhů“
//   (vzor stavu Dostupnosti). Soubory v repozitáři se nemění, PR nevzniká: změnu pravidel udělá AI až na pokyn
//   vlastníka jako běžné zadání přes bránu.
// - Model dostane jen čísla PR/issue, zkrácené titulky a zkrácené úryvky komentářů bez účtů, zmínek, e-mailů
//   a telefonů (CLAUDE.md, pravidlo 4). Totéž čištění projde i výstup modelu, než jde do přehledu.
// - Selhání prostředí (limit modelu, výpadek API, vypršený čas) se vypíše zvlášť a do signálů selhání agenta
//   se nepočítá.
// - Bez klíče nebo při selhání modelu zůstane oddíl jen s výpisem signálů.

import fs from 'node:fs';
