/** Text pravidel pro model: CLAUDE.md a seznam skills s popisem z hlavičky (z checkoutu main). */
export function nactiPravidla(koren = new URL('../../', import.meta.url)) {
  const claude = fs.readFileSync(new URL('CLAUDE.md', koren), 'utf8').slice(0, 14000);
  const slozka = new URL('.claude/skills/', koren);
  const skills = fs.existsSync(slozka)
    ? fs.readdirSync(slozka).filter((n) => fs.existsSync(new URL(`${n}/SKILL.md`, slozka))).map((n) => {
      const popis = fs.readFileSync(new URL(`${n}/SKILL.md`, slozka), 'utf8').match(/^description:\s*(.+)$/m)?.[1] || '';
      return `- .claude/skills/${n}/SKILL.md: ${popis.slice(0, 300)}`;
    })
    : [];
  return `## CLAUDE.md\n\n${claude}\n\n## Skills\n\n${skills.join('\n')}`;
}

const radekSignalu = (s) => `- ${s.druh} ${s.pr ? 'PR' : 'issue'} #${s.cislo}${s.titulek ? ` „${s.titulek}“` : ''}`
  + `${s.kol ? `, kol oprav ${s.kol}` : ''}${s.kontrola ? `, kontrola ${bezpecnyUryvek(s.kontrola, 60)}` : ''}${s.text ? `: ${s.text}` : ''}`;

