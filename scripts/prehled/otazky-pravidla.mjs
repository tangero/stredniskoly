// Otázka třikrát = pravidlo (#306, rozhodnutí vlastníka 3. 11. 2026): projde otázky na vlastníka zodpovězené
// za posledních 60 dní a najde skupiny podobných otázek, na které vlastník odpověděl aspoň dvakrát stejně.
// Takovou skupinu AI navrhne jako trvalé pravidlo do týdenní dávky H2 (#560). Skript jen čte GitHub
// a skládá podklad; znění pravidla píše AI a nic neplatí bez souhlasu vlastníka s dávkou.
//
//   node scripts/prehled/otazky-pravidla.mjs --seznam        kandidáti na pravidlo (JSON)
//   node scripts/prehled/otazky-pravidla.mjs --navrh         podklad návrhu do dávky H2 (Markdown)
//   [--dni 60] [--prah 0.6]
//
// Otázka je komentář s nadpisem „Otázka pro vlastníka“ (CLAUDE.md, pravidlo 8). Odpověď je první další komentář
// v témže issue: komentář vlastníka bez patičky AI a bez značky automatiky, nebo komentář s nadpisem „Odpověď
// vlastníka“ od vlastníka či asistenta zadání (zápis odpovědi z rozhovoru).

import { pathToFileURL } from 'node:url';
import { REPO, vytvorApi } from '../brana/data.mjs';
import { podobnost } from '../review/stagnace.mjs';
import { odstranOsobni } from '../provoz/triaz.mjs';

const DEN = 24 * 60 * 60 * 1000;
export const OBDOBI_DNI = 60;
export const PRAH = 0.6;
export const MAX_URYVEK = 300;

const NADPIS_OTAZKY = /^#{1,6}\s*Otázka pro vlastníka\b/im;
const NADPIS_ODPOVEDI = /^#{1,6}\s*Odpověď vlastníka\b/im;
const PATICKA_AI = /Generated by \[?Claude Code|^_?Zapsal [\w ]*Code/im;
const ZNACKA_AUTOMATIKY = /<!--/;

/** Text bez nadpisu otázky či odpovědi, patičky a značek, na jednom řádku. */
export function jadro(telo = '') {
  return String(telo)
    .replace(/<!--[\s\S]*?-->/g, ' ')
    .split(/\r?\n/)
    .filter((r) => !NADPIS_OTAZKY.test(r) && !NADPIS_ODPOVEDI.test(r))
    .join('\n')
    .replace(/\n-{3,}\s*\n[\s\S]*$/, '')
    .replace(/\s+/g, ' ')
    .trim();
}

export function jeOtazka(k, vlastnik) {
  return k.autor === vlastnik && NADPIS_OTAZKY.test(k.telo || '');
}

export function jeOdpoved(k, vlastnik, asistent) {
  const telo = k.telo || '';
  if (NADPIS_OTAZKY.test(telo)) return false;
  if (NADPIS_ODPOVEDI.test(telo)) return k.autor === vlastnik || k.autor === asistent;
  return k.autor === vlastnik && !PATICKA_AI.test(telo) && !ZNACKA_AUTOMATIKY.test(telo);
}

/**
 * Dvojice otázka–odpověď z komentářů jednoho issue (seřazených podle času). Otázka bez odpovědi se vynechá,
 * nová otázka před odpovědí nahradí předchozí. Jen odpovědi od `od` (Date) dál.
 */
export function dvojice(cislo, komentare = [], { vlastnik, asistent, od = new Date(0) } = {}) {
  const vysledek = [];
  let otazka = null;
  for (const k of komentare) {
    if (jeOtazka(k, vlastnik)) {
      otazka = k;
    } else if (otazka && jeOdpoved(k, vlastnik, asistent)) {
      if (new Date(k.vytvoreno) >= od) {
        vysledek.push({
          cislo, otazka: jadro(otazka.telo), odpoved: jadro(k.telo), url: k.url || otazka.url, datum: k.vytvoreno,
        });
      }
      otazka = null;
    }
  }
  return vysledek;
}

/** Volba z odpovědi, když začíná výběrem varianty („A“, „(B)“, „Varianta 2“, „ano“, „ne“); jinak null. */
export function volba(odpoved = '') {
  const t = String(odpoved).normalize('NFD').replace(/[̀-ͯ]/g, '').toLowerCase().trim();
  let m;
  if ((m = t.match(/^varianta\s+\(?([a-e1-5])\)?(?=$|[\s.,:;)!-])/))) return m[1];
  if ((m = t.match(/^\(?([a-e])\)?(?=$|[\s.,:;)!-])/))) return m[1];
  if ((m = t.match(/^(ano|ne)\b/))) return m[1];
  return null;
}

export function stejnaOdpoved(a, b, prah = PRAH) {
  const va = volba(a);
  const vb = volba(b);
  if (va || vb) return va === vb;
  return podobnost(a, b) >= prah;
}

/**
 * Kandidáti na pravidlo: skupiny aspoň dvou zodpovězených otázek z různých issues, kde každá dvojice ve skupině
 * je spojená podobnou otázkou (`podobnost` ≥ práh) a stejnou odpovědí. Seřazeno od největší skupiny.
 */
export function kandidati(seznam = [], prah = PRAH) {
  const rodic = seznam.map((_, i) => i);
  const koren = (i) => (rodic[i] === i ? i : (rodic[i] = koren(rodic[i])));
  for (let i = 0; i < seznam.length; i += 1) {
    for (let j = i + 1; j < seznam.length; j += 1) {
      const a = seznam[i];
      const b = seznam[j];
      if (a.cislo === b.cislo) continue;
      if (podobnost(a.otazka, b.otazka) >= prah && stejnaOdpoved(a.odpoved, b.odpoved, prah)) {
        rodic[koren(i)] = koren(j);
      }
    }
  }
  const skupiny = new Map();
  seznam.forEach((d, i) => {
    const k = koren(i);
    if (!skupiny.has(k)) skupiny.set(k, []);
    skupiny.get(k).push(d);
  });
  return [...skupiny.values()]
    .filter((s) => new Set(s.map((d) => d.cislo)).size >= 2)
    .map((s) => s.sort((a, b) => String(a.datum).localeCompare(String(b.datum))))
    .sort((a, b) => b.length - a.length || a[0].cislo - b[0].cislo);
}

const uryvek = (t) => {
  const s = odstranOsobni(t);
  return s.length > MAX_URYVEK ? `${s.slice(0, MAX_URYVEK - 1)}…` : s;
};

/** Podklad návrhu do týdenní dávky H2. Znění pravidla doplní AI; bez kandidátů jedna věta. */
export function sestavNavrh(skupiny = [], { dni = OBDOBI_DNI } = {}) {
  const radky = [
    `## Otázka třikrát = pravidlo (#306)`,
    '',
    `Otázky na vlastníka zodpovězené za posledních ${dni} dní, na které vlastník odpověděl aspoň dvakrát stejně.`,
    'Každá skupina je kandidát na trvalé pravidlo; platí až se souhlasem vlastníka s dávkou.',
    '',
  ];
  if (!skupiny.length) {
    radky.push('Žádná skupina podobných otázek se stejnou odpovědí.');
    return `${radky.join('\n')}\n`;
  }
  skupiny.forEach((s, i) => {
    radky.push(`### Kandidát ${i + 1}`, '', 'Znění pravidla: _(doplní AI z odpovědí níže)_', '');
    for (const d of s) {
      radky.push(`- #${d.cislo} (${String(d.datum).slice(0, 10)}${d.url ? `, ${d.url}` : ''})`);
      radky.push(`  - Otázka: ${uryvek(d.otazka)}`);
      radky.push(`  - Odpověď: ${uryvek(d.odpoved)}`);
    }
    radky.push('');
  });
  return `${radky.join('\n')}\n`;
}

async function vsechnyStrany(api, cesta) {
  const vse = [];
  for (let strana = 1; strana <= 20; strana += 1) {
    const dil = await api(`${cesta}${cesta.includes('?') ? '&' : '?'}per_page=100&page=${strana}`);
    vse.push(...dil);
    if (dil.length < 100) break;
  }
  return vse;
}

async function nactiDvojice(api, { dni, ted = new Date() }) {
  const yaml = (await import('js-yaml')).default;
  const rezimy = yaml.load(Buffer.from((await api(`repos/${REPO}/contents/.github/rezimy.yml?ref=main`)).content, 'base64').toString('utf8'));
  const od = new Date(ted.getTime() - dni * DEN);
  const nedavne = await vsechnyStrany(api, `repos/${REPO}/issues/comments?since=${od.toISOString()}`);
  const cisla = [...new Set(nedavne
    .filter((k) => jeOdpoved({ autor: k.user?.login, telo: k.body || '' }, rezimy.vlastnik, rezimy.asistent))
    .map((k) => Number(String(k.issue_url).split('/').pop())))];
  const vse = [];
  for (const cislo of cisla) {
    const komentare = (await vsechnyStrany(api, `repos/${REPO}/issues/${cislo}/comments`)).map((k) => ({
      autor: k.user?.login, telo: k.body || '', vytvoreno: k.created_at, url: k.html_url,
    }));
    vse.push(...dvojice(cislo, komentare, { vlastnik: rezimy.vlastnik, asistent: rezimy.asistent, od }));
  }
  return vse;
}

async function main() {
  const argv = process.argv.slice(2);
  const hodnota = (nazev, vychozi) => {
    const i = argv.indexOf(nazev);
    return i >= 0 && argv[i + 1] ? Number(argv[i + 1]) : vychozi;
  };
  const dni = hodnota('--dni', OBDOBI_DNI);
  const prah = hodnota('--prah', PRAH);
  if (!argv.includes('--seznam') && !argv.includes('--navrh')) {
    console.error('Použití: --seznam | --navrh [--dni 60] [--prah 0.6]');
    process.exit(2);
  }
  const skupiny = kandidati(await nactiDvojice(vytvorApi(), { dni }), prah);
  if (argv.includes('--seznam')) return console.log(JSON.stringify(skupiny, null, 2));
  return process.stdout.write(sestavNavrh(skupiny, { dni }));
}

if (import.meta.url === pathToFileURL(process.argv[1] || '').href) {
  main().catch((e) => {
    console.error(e);
    process.exit(1);
  });
}
