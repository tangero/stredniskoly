import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  tyden, navrhyKRozhodnuti, ctiAkci, sestavTelo, doporuceniZTela, ctiRozhodnuti, komentarVlastnika,
} from '../scripts/prehled/navrhy-tyden.mjs';

// Týdenní issue návrhů od veřejnosti (RA55, #564, K3). Smyšlená data, bez sítě.
const POLOZKY = [
  { cislo: 701, titulek: 'Řazení škol podle vzdálenosti', proLidi: 'Rodina uvidí nejbližší školy nahoře.', doporuceni: 'zařadit do celku #277' },
  { cislo: 702, titulek: 'Tmavý režim', proLidi: 'Web půjde číst v noci.', doporuceni: 'odložit' },
  { cislo: 703, titulek: 'Hodnocení učitelů', proLidi: 'Návštěvník by hodnotil učitele.', doporuceni: 'zamítnout (osobní údaje zaměstnanců škol)' },
  { cislo: 704, titulek: 'Porovnání oborů', proLidi: 'Dva obory vedle sebe.', doporuceni: 'spojit s #650' },
];

test('týden podle ISO 8601', () => {
  assert.equal(tyden(new Date('2026-11-09T08:00:00Z')), '2026-46');
  assert.equal(tyden(new Date('2027-01-01T08:00:00Z')), '2026-53');
  assert.equal(tyden(new Date('2027-01-04T08:00:00Z')), '2027-01');
});

test('do týdenního issue jdou jen otevřené feature-request bez rozhodnutí', () => {
  const issues = [
    { cislo: 3, stitky: ['feature-request'] },
    { cislo: 1, stitky: ['feature-request', 'oblast:detail'] },
    { cislo: 2, stitky: ['feature-request', 'zamitnuto'] },
    { cislo: 4, stitky: ['bug-report'] },
    { cislo: 5, stitky: ['feature-request', 'schvaleno'] },
    { cislo: 6, stitky: ['feature-request'], stav: 'closed' },
    { cislo: 7, stitky: ['feature-request'], pull_request: {} },
  ];
  assert.deepEqual(navrhyKRozhodnuti(issues).map((i) => i.cislo), [1, 3]);
});

test('doporučení má jeden ze čtyř tvarů, zamítnutí jen s důvodem', () => {
  assert.deepEqual(ctiAkci('zařadit do celku #306'), { akce: 'zaradit', celek: 306 });
  assert.deepEqual(ctiAkci('Spojit s #12'), { akce: 'spojit', s: 12 });
  assert.deepEqual(ctiAkci('odložit'), { akce: 'odlozit' });
  assert.deepEqual(ctiAkci('zamítnout (mimo směr vývoje)'), { akce: 'zamitnout', duvod: 'mimo směr vývoje' });
  assert.equal(ctiAkci('zamítnout'), null);
  assert.equal(ctiAkci('udělat hned'), null);
  assert.throws(() => sestavTelo({ tyden: '2026-46', polozky: [{ ...POLOZKY[0], doporuceni: 'nevím' }] }), /#701/);
});

test('tělo issue nese u každého návrhu Pro lidi a doporučení, které jde zpětně přečíst', () => {
  const telo = sestavTelo({ tyden: '2026-46', polozky: POLOZKY });
  assert.match(telo, /Týden 2026-46/);
  assert.match(telo, /^Pro lidi: /m);
  for (const p of POLOZKY) assert.match(telo, new RegExp(`^- #${p.cislo} `, 'm'));
  assert.equal((telo.match(/^ {2}- Pro lidi:/gm) || []).length, 4);
  const dop = doporuceniZTela(telo);
  assert.deepEqual(dop.get(701), { akce: 'zaradit', celek: 277 });
  assert.deepEqual(dop.get(703), { akce: 'zamitnout', duvod: 'osobní údaje zaměstnanců škol' });
  assert.equal(dop.size, 4);
  assert.match(sestavTelo({ tyden: '2026-47', polozky: [] }), /žádný návrh nečeká/);
});

test('rozhodnutí vlastníka: podle doporučení, vlastní řádky a přenos nerozhodnutých', () => {
  const dop = doporuceniZTela(sestavTelo({ tyden: '2026-46', polozky: POLOZKY }));
  const vse = ctiRozhodnuti('Podle doporučení.', dop).rozhodnuti;
  assert.deepEqual([...vse.keys()].sort(), [701, 702, 703, 704]);
  assert.equal(vse.get(704).akce, 'spojit');

  const zmena = ctiRozhodnuti('podle doporučení, jen\n#702 zařadit do #306\n#703 odložit', dop).rozhodnuti;
  assert.deepEqual(zmena.get(702), { akce: 'zaradit', celek: 306 });
  assert.equal(zmena.get(703).akce, 'odlozit');
  assert.equal(zmena.get(701).akce, 'zaradit');

  const jen = ctiRozhodnuti('- #701 zamítnout (nemáme data)\n#704 něco jiného', dop);
  assert.deepEqual(jen.rozhodnuti.get(701), { akce: 'zamitnout', duvod: 'nemáme data' });
  assert.equal(jen.rozhodnuti.get(702).akce, 'odlozit');
  assert.equal(jen.rozhodnuti.get(704).akce, 'odlozit');
  assert.deepEqual(jen.nejasne, ['#704 něco jiného']);
});

test('komentář vlastníka: bez patičky AI, nebo zápis s nadpisem Odpověď vlastníka', () => {
  const ai = { autor: 'tangero', telo: 'Shrnutí.\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_' };
  const vlastnik = { autor: 'tangero', telo: 'podle doporučení' };
  const zapis = { autor: 'eduarda-prijimacky', telo: '## Odpověď vlastníka\n#701 odložit' };
  const cizi = { autor: 'nekdo', telo: '#701 zařadit do #306' };
  assert.equal(komentarVlastnika([vlastnik, ai, cizi]), vlastnik);
  assert.equal(komentarVlastnika([vlastnik, zapis, cizi]), zapis);
  assert.equal(komentarVlastnika([ai, cizi]), null);
});
