import { test } from 'node:test';
import assert from 'node:assert/strict';
import {
  jadro, jeOdpoved, dvojice, volba, stejnaOdpoved, kandidati, sestavNavrh,
} from '../scripts/prehled/otazky-pravidla.mjs';

// Otázka třikrát = pravidlo (#306). Smyšlená data, bez sítě.
const V = 'vlastnik-ucet';
const A = 'asistent-ucet';
const PATICKA = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
const OTAZKA_ZAMRZNUTI = '## Otázka pro vlastníka\n\nPR čeká na sloučení během zamrznutí. Mám opravu překlepu v textu stránky školy pustit jako incident, nebo počkat na konec zamrznutí?'
  + PATICKA;

const k = (autor, telo, den) => ({ autor, telo, vytvoreno: `2026-11-${String(den).padStart(2, '0')}T08:00:00Z` });

test('jádro komentáře je bez nadpisu, patičky a značek', () => {
  assert.equal(jadro(`${OTAZKA_ZAMRZNUTI}\n<!-- x -->`).startsWith('PR čeká na sloučení'), true);
  assert.equal(jadro(OTAZKA_ZAMRZNUTI).includes('Generated'), false);
  assert.equal(jadro('### Odpověď vlastníka\n\nPočkat.'), 'Počkat.');
});

test('odpověď je komentář vlastníka bez patičky, nebo zápis s nadpisem od vlastníka či asistenta', () => {
  assert.equal(jeOdpoved(k(V, 'Počkat na konec.', 1), V, A), true);
  assert.equal(jeOdpoved(k(V, `Počkat.${PATICKA}`, 1), V, A), false);
  assert.equal(jeOdpoved(k(V, 'Žádost o vyhodnocení.\n<!-- brana:pred-sloucenim -->', 1), V, A), false);
  assert.equal(jeOdpoved(k(A, '## Odpověď vlastníka\nPočkat.', 1), V, A), true);
  assert.equal(jeOdpoved(k(A, 'Počkat.', 1), V, A), false);
  assert.equal(jeOdpoved(k('cizi-ucet', '## Odpověď vlastníka\nAno.', 1), V, A), false);
});

test('dvojice otázka–odpověď v issue, bez nezodpovězených a starých odpovědí', () => {
  const komentare = [
    k(V, OTAZKA_ZAMRZNUTI, 1),
    k('cizi-ucet', 'Taky by mě to zajímalo.', 2),
    k(V, 'Počkat na konec zamrznutí.', 3),
    k(V, OTAZKA_ZAMRZNUTI, 4),
  ];
  const d = dvojice(10, komentare, { vlastnik: V, asistent: A });
  assert.equal(d.length, 1);
  assert.equal(d[0].odpoved, 'Počkat na konec zamrznutí.');
  assert.equal(dvojice(10, komentare, { vlastnik: V, asistent: A, od: new Date('2026-11-05') }).length, 0);
});

test('volba varianty a stejná odpověď', () => {
  assert.equal(volba('(B) nechat jen v přehledu'), 'b');
  assert.equal(volba('A.'), 'a');
  assert.equal(volba('Varianta 2, ale bez e-mailu'), '2');
  assert.equal(volba('Ano, zapiš to.'), 'ano');
  assert.equal(volba('Počkat na konec zamrznutí.'), null);
  assert.equal(stejnaOdpoved('B', '(B) jen přehled'), true);
  assert.equal(stejnaOdpoved('A', 'B'), false);
  assert.equal(stejnaOdpoved('Počkat na konec zamrznutí.', 'Počkat na konec zamrznutí, prosím.'), true);
});

test('kandidát vznikne ze dvou podobných otázek v různých issues se stejnou odpovědí', () => {
  const q = jadro(OTAZKA_ZAMRZNUTI);
  const q2 = q.replace('překlepu', 'chyby');
  const seznam = [
    { cislo: 11, otazka: q, odpoved: 'Počkat na konec zamrznutí.', datum: '2026-10-01' },
    { cislo: 12, otazka: q2, odpoved: 'Počkat na konec zamrznutí.', datum: '2026-10-20' },
    { cislo: 13, otazka: q, odpoved: 'Pustit jako incident.', datum: '2026-10-25' },
    { cislo: 14, otazka: 'Mám zapsat neotevírá pro obory školy pro přijímání 2027?', odpoved: 'Počkat na konec zamrznutí.', datum: '2026-10-26' },
  ];
  const s = kandidati(seznam);
  assert.equal(s.length, 1);
  assert.deepEqual(s[0].map((d) => d.cislo), [11, 12]);
});

test('dvě odpovědi v témže issue kandidáta netvoří', () => {
  const q = jadro(OTAZKA_ZAMRZNUTI);
  const seznam = [
    { cislo: 11, otazka: q, odpoved: 'Počkat.', datum: '2026-10-01' },
    { cislo: 11, otazka: q, odpoved: 'Počkat.', datum: '2026-10-02' },
  ];
  assert.deepEqual(kandidati(seznam), []);
});

test('podklad návrhu odkazuje na otázky a nevypíše e-mail', () => {
  const navrh = sestavNavrh([[
    { cislo: 11, otazka: 'Napsat škole na skola@example.cz?', odpoved: 'Ne.', datum: '2026-10-01T08:00:00Z', url: 'https://example.cz/11' },
    { cislo: 12, otazka: 'Napsat škole?', odpoved: 'Ne.', datum: '2026-10-02T08:00:00Z' },
  ]]);
  assert.match(navrh, /### Kandidát 1/);
  assert.match(navrh, /- #11 \(2026-10-01, https:\/\/example\.cz\/11\)/);
  assert.equal(navrh.includes('skola@example.cz'), false);
  assert.match(sestavNavrh([]), /Žádná skupina/);
});
