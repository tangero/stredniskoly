const TED = Date.parse('2026-10-08T07:00:00Z');
const DNES = '2026-10-08';
const ucty = { vlastnik: 'tangero', asistent: 'eduarda-prijimacky' };
const PATICKA = '\n\n---\n_Generated by [Claude Code](https://claude.ai/code)_';
const TELO_PR = 'Closes #10\n\n## Pro vlastníka\nMísto krátkého jména Gymnazium uvidíš celý oficiální název školy.\nAdresa: /skola/600001234-gymnazium\n\n## Jak ověřit\nnic';
const pr = (o = {}) => ({ cislo: 5, od: '2026-10-07T07:00:00Z', titulek: 'Celé názvy škol', telo: TELO_PR, stitky: [], souhlas: true, nahled: 'https://stredniskoly-abc.vercel.app', ...o });
const issue = (o = {}) => ({ cislo: 20, titulek: 'Návrh', telo: 'Zdroj: vlastník\n\n## Problém\nRodiče nevidí body na první pohled.', stitky: ['interni', 'navrh'], komentare: [], upraveno: '2026-10-07T00:00:00Z', ...o });
const skupiny = (o) => sestavSkupiny({ prs: [], issues: [], ucty, dnes: DNES, ted: TED, ...o });

test('PR ke schválení: lidská věta z oddílu Pro vlastníka a odkaz na stránku v náhledu', () => {
  const p = polozkaPr(pr(), { nahled: 'https://stredniskoly-abc.vercel.app' });
  assert.match(p.radky[0], /^Na stránce <a href="https:\/\/stredniskoly-abc\.vercel\.app\/skola\/600001234-gymnazium">\/skola\/600001234-gymnazium<\/a> zkontroluj: Místo krátkého jména Gymnazium/);
  assert.doesNotMatch(p.radky[0], /Adresa:/);
  // Bez náhledu jen cesta jako text a vysvětlení.
  const bez = polozkaPr(pr(), { nahled: null });
  assert.match(bez.radky[0], /<code>\/skola\/600001234-gymnazium<\/code>/);
  assert.match(bez.radky[1], /Náhled zatím není/);
});

test('skupiny v pořadí pro vlastníka, prázdné se vynechají', () => {
  const g = skupiny({
    prs: [pr(), pr({ cislo: 6, souhlas: false, stitky: ['potrebuje-cloveka'] }), pr({ cislo: 7, souhlas: false })],
    issues: [
      issue(),
      issue({ cislo: 21, stitky: ['interni', 'otazka'], komentare: [{ autor: 'tangero', telo: `Mám použít data za rok 2026, nebo 2025?${PATICKA}` }] }),
      issue({ cislo: 22, komentare: [{ autor: 'github-actions[bot]', telo: '## Oponentura\n\nVarianty A a B.' }] }),
      issue({ cislo: 23, stitky: ['interni', 'pripominka'], telo: 'Termín: 2026-10-08\n\nVyhodnotit sklizeň.' }),
      issue({ cislo: 24, stitky: ['interni', 'pripominka'], telo: 'Termín: 2026-11-01\n\nPozději.' }),
      issue({ cislo: 25, stitky: ['interni', 'navrh', 'zamitnuto'] }),
    ],
  });
  assert.deepEqual(g.map((x) => x.klic), ['souhlas', 'otazka', 'oponentura', 'navrh', 'pripominka', 'clovek']);
  assert.deepEqual(g.map((x) => x.polozky.map((p) => p.cislo)), [[5], [21], [22], [20], [23], [6]]);
  assert.match(g[1].polozky[0].radky[0], /Mám použít data za rok 2026/);
  assert.doesNotMatch(g[1].polozky[0].radky[0], /Generated by/);
  assert.equal(g[3].polozky[0].radky[0], 'Rodiče nevidí body na první pohled.');
});

