test('zpráva: HTML Telegramu, tlačítka dvě na řádek, strop položek a tlačítek', () => {
  const g = skupiny({ prs: Array.from({ length: 20 }, (_, i) => pr({ cislo: 100 + i, titulek: `Změna <${i}> & spol.` })) });
  const z = zprava(g, { ted: TED });
  assert.match(z.text, /^<b>Čeká na tebe: 20<\/b>/);
  assert.match(z.text, /Změna &lt;0&gt; &amp; spol\./);
  assert.match(z.text, new RegExp(`…a dalších ${20 - MAX_V_SKUPINE}`));
  assert.match(z.text, /Co udělat<\/b>\n.*Když sedí, přidej na PR štítek <code>schvaleno<\/code>/);
  const vsechna = z.tlacitka.flat();
  assert.equal(vsechna.length, MAX_V_SKUPINE);
  assert.ok(vsechna.length <= MAX_TLACITEK);
  assert.ok(z.tlacitka.every((r) => r.length <= 2));
  assert.deepEqual(vsechna[0], { text: '#100 schválit', url: 'https://github.com/tangero/stredniskoly/pull/100' });
  assert.ok(z.text.length < 4096);
});

test('pomocné funkce', () => {
  assert.equal(html('a < b & "c"'), 'a &lt; b &amp; &quot;c&quot;');
  assert.equal(terminPripominky('Termín: 2026-10-08'), '2026-10-08');
  assert.equal(terminPripominky('bez'), null);
  assert.equal(uvodIssue('Zdroj: vlastník\n\n## Rozsah\n- [ ] K1: x\n\nText **tučně** a [odkaz](https://x).'), 'Text tučně a odkaz.');
  assert.equal(potrebujeSouhlas({ conclusion: 'failure', output: { summary: '- mění pravomoci AI (x): chybí souhlas vlastníka (bez štítku)' } }), true);
  assert.equal(potrebujeSouhlas({ conclusion: 'failure', output: { summary: '- chybí review asistenta zadání' } }), false);
  assert.equal(potrebujeSouhlas({ conclusion: 'success', output: { summary: '- chybí souhlas vlastníka' } }), false);
  assert.equal(potrebujeSouhlas(undefined), false);
  const k = { conclusion: 'failure', output: { summary: '- kontrolovaná činnost (workflows): chybí souhlas vlastníka (PR nemá štítek schvaleno)\n- souhlas na issue #10 neplatí: bez štítku schvaleno' } };
  assert.equal(potrebujeSouhlas(k), true);
  assert.equal(rozpracovanyBezSouhlasu(k), false);
});

