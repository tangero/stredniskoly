test('ranní zpráva: nahoře přes 3 dny od nejstarší, pak nové, zbytek jen počty (#562)', () => {
  const dnu = (n) => new Date(TED - n * 86400000).toISOString();
  const g = skupiny({ issues: [
    issue({ cislo: 40, vytvoreno: dnu(5), stitky: ['bug-report'] }),
    issue({ cislo: 41, vytvoreno: dnu(9), stitky: ['bug-report'] }),
    issue({ cislo: 42, stitky: ['interni', 'otazka'], stitkyOd: { otazka: dnu(0.2) }, komentare: [{ autor: 'tangero', telo: `Který rok?${PATICKA}` }] }),
    issue({ cislo: 43, vytvoreno: dnu(1), stitky: ['bug-report'] }),
  ] });
  const z = zprava(g, { ted: TED, posledni: TED - 86400000 / 2 });
  const t = z.text;
  assert.ok(t.indexOf('Čeká přes 3 dny') < t.indexOf('Nové od minulé zprávy') && t.indexOf('Nové od minulé zprávy') < t.indexOf('Ostatní'));
  assert.ok(t.indexOf('#41') < t.indexOf('#40'), 'nejstarší první');
  assert.match(t, /\(hlášení, 9 dní\)/);
  assert.match(t, /Hlášení od veřejnosti: 1/);
  assert.doesNotMatch(t, /Který rok.*Který rok/);
});

